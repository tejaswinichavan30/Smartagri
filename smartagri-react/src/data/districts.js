const GENERIC_CROP_STOPWORDS = new Set([
  'gram', 'bean', 'beans', 'peas', 'crop', 'plant', 'leaf', 'seed', 'fruit', 'tree', 'nut'
]);

export function matchCropKey(input) {
  if (!input) return '';
  const str = String(input).trim();
  const lower = str.toLowerCase();
  const clean = lower.replace(/[^a-z0-9]/g, '');

  // 1. Direct match in canonical aliases
  if (CANONICAL_CROP_ALIASES[lower]) return CANONICAL_CROP_ALIASES[lower];
  if (CANONICAL_CROP_ALIASES[clean]) return CANONICAL_CROP_ALIASES[clean];

  // Also check if any alias is contained as a distinct phrase
  for (const [alias, canonical] of Object.entries(CANONICAL_CROP_ALIASES)) {
    if (lower === alias || lower.startsWith(alias + ' ') || lower.includes(' ' + alias) || lower.includes('(' + alias) || clean === alias.replace(/[^a-z0-9]/g, '')) {
      return canonical;
    }
  }

  // 2. Direct match in CROPS
  const exact = CROPS.find(c => c.toLowerCase() === lower);
  if (exact) return exact;

  // 3. Alphanumeric match in CROPS (handles e.g. "Rice (Paddy)" -> "Rice")
  const cleanMatch = CROPS.find(c => {
    const cClean = c.toLowerCase().replace(/[^a-z0-9]/g, '');
    return cClean === clean || clean === cClean;
  });
  if (cleanMatch) return cleanMatch;

  // 4. Match across translations (Kannada, Hindi, English variants)
  for (const [key, tr] of Object.entries(CROP_TRANSLATIONS)) {
    for (const val of Object.values(tr)) {
      const valLower = String(val).toLowerCase();
      if (str === val || valLower === lower) {
        return key;
      }
      const words = valLower.split(/[\s\(\)\/\-,]+/);
      for (const w of words) {
        if (w.length >= 4 && !GENERIC_CROP_STOPWORDS.has(w) && (lower.includes(w) || w.includes(lower))) {
          return key;
        }
      }
    }
  }

  return exact || cleanMatch || str;
}

export function matchDistrictKey(input) {
  if (!input) return '';
  const str = String(input).trim();
  const lower = str.toLowerCase();
  const clean = lower.replace(/[^a-z0-9]/g, '');

  const exact = DISTRICTS.find(d => d.toLowerCase() === lower);
  if (exact) return exact;

  const cleanMatch = DISTRICTS.find(d => {
    const dClean = d.toLowerCase().replace(/[^a-z0-9]/g, '');
    return dClean === clean || clean.includes(dClean) || dClean.includes(clean);
  });
  if (cleanMatch) return cleanMatch;

  for (const [key, tr] of Object.entries(DISTRICT_TRANSLATIONS)) {
    for (const val of Object.values(tr)) {
      const valLower = String(val).toLowerCase();
      if (str.includes(val) || val.includes(str) || valLower.includes(lower) || lower.includes(valLower)) {
        return key;
      }
    }
  }

  return exact || cleanMatch || str;
}

