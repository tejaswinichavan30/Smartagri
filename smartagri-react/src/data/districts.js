export function getCropName(crop, lang = 'en') {
  if (!crop) return '';
  const tr = CROP_TRANSLATIONS[crop];
  if (tr && tr[lang]) return tr[lang];
  // Case-insensitive lookup
  const cropLower = crop.toLowerCase().trim();
  const match = Object.keys(CROP_TRANSLATIONS).find(k => k.toLowerCase() === cropLower);
  if (match && CROP_TRANSLATIONS[match][lang]) return CROP_TRANSLATIONS[match][lang];
  return crop;
}

export function getCropDropdownLabel(crop, lang = 'en') {
  if (!crop) return '';
  const cropLower = crop.toLowerCase().trim();
  const matchKey = Object.keys(CROP_TRANSLATIONS).find(k => k.toLowerCase() === cropLower) || crop;
  const tr = CROP_TRANSLATIONS[matchKey];
  const enName = tr?.en || crop;
  const cleanEn = enName.replace(/\s*\([^)]*\)/, '').trim();

  if (lang === 'kn') {
    const knName = tr?.kn;
    if (knName) {
      const cleanKn = knName.replace(/\s*\([^)]*\)/, '').trim();
      return `${cleanEn} (${cleanKn})`;
    }
  } else if (lang === 'hi') {
    const hiName = tr?.hi;
    if (hiName) {
      const cleanHi = hiName.replace(/\s*\([^)]*\)/, '').trim();
      return `${cleanEn} (${cleanHi})`;
    }
  }
  return cleanEn;
}

